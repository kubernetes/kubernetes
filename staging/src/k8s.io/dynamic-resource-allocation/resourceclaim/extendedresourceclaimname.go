package resourceclaim

import (
	"crypto/sha256"
	"encoding/hex"

	"k8s.io/apimachinery/pkg/types"
)

const (
	// extendedResourceClaimNameMaxLength matches the limit of names generated
	// with generateName
	extendedResourceClaimNameMaxLength = 63

	// extendedResourceClaimNameSuffixLength is the number of hex characters of
	// the pod UID hash in the suffix. Pods with long names that share a prefix share
	// the truncated base, and only the suffix tells their claims apart.
	extendedResourceClaimNameSuffixLength = 10
)

// ExtendedResourceClaimName returns the name of the ResourceClaim that the
// scheduler creates for the extended resources of a pod which are backed by
// DRA, if the devices allocated for that claim consume node allocatable
// resources. Otherwise the apiserver generates the name.
//
// The name is derived from the pod rather than generated by the apiserver,
// so that pod.status.extraNodeAllocatableResources can reference the claim
// before the claim exists. Pod status validation recomputes the name to check
// such references. The scheduler and the apiserver may run different
// versions, so the derivation must never change.
//
// The name has the same form and length limit as a generated name.
// TODO(pravk03): explore if its possible to use this name even without node allocatable
// resources in the extended resource claim.
func ExtendedResourceClaimName(podName string, podUID types.UID) string {
	sum := sha256.Sum256([]byte(podUID))
	suffix := hex.EncodeToString(sum[:])[:extendedResourceClaimNameSuffixLength]
	base := podName + "-extended-resources-"
	if maxBaseLength := extendedResourceClaimNameMaxLength - len(suffix); len(base) > maxBaseLength {
		base = base[:maxBaseLength]
	}
	return base + suffix
}
