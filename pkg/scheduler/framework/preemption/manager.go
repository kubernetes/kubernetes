type defaultPreemptionManager struct {
	snapshot  fwk.SharedLister
	executor  fwk.PreemptionExecutor
	pdbLister policylisters.PodDisruptionBudgetLister
}

var _ fwk.PreemptionManager = &defaultPreemptionManager{}
var _ fwk.ReprieveFilter = &defaultPreemptionManager{}

// NewPreemptionManager creates a PreemptionManager using the provided handle
// and features for victim discovery and actuation.
func NewPreemptionManager(fh fwk.Handle, fts feature.Features) fwk.PreemptionManager {
	return &defaultPreemptionManager{
		snapshot:  fh.SnapshotSharedLister(),
		executor:  NewExecutor(fh, fts),
		pdbLister: fh.SharedInformerFactory().Policy().V1().PodDisruptionBudgets().Lister(),
	}
}

// GenerateVictims creates victims with grouping determined by the hierarchy's DisruptionPolicy and ordering determined by Priority and PDB violations.
func (m *defaultPreemptionManager) GenerateVictims(ctx context.Context, pgInfo fwk.PodGroupInfo) ([]fwk.PreemptionVictim, *fwk.Status) {
	logger := klog.FromContext(ctx)

	if getPreemptionPolicy(pgInfo) == v1.PreemptNever {
		msg := "not eligible due to preemptionPolicy=Never."
		logger.V(5).Info("Preemptor is not eligible for preemption", "preemptor", klog.KObj(pgInfo), "type", pgInfo.GetType(), "reason", msg)
		return nil, fwk.NewStatus(fwk.Unschedulable, msg)
	}

	victims, err := getWorkloadPreemptionVictims(logger, m.snapshot)
	if err != nil {
		return nil, fwk.AsStatus(fmt.Errorf("failed to get victims: %w", err))
	}

	pdbs, err := getPodDisruptionBudgets(m.pdbLister)
	if err != nil {
		return nil, fwk.AsStatus(fmt.Errorf("failed to get pod disruption budgets: %w", err))
	}

	return prepareDomainVictims(victims, pgInfo.GetPriority(), pdbs), nil
}

// CompareVictimSets compares the preemption cost of two victim sets by applying the following criteria in order:
//  1. Total PDB violations: fewer PDB-violating pods across the set is preferred.
//  2. Priority bands (descending): at the highest priority level where the sets differ,
//     a lower priority or fewer evicted pods at that priority is preferred (a set with
//     no remaining victims is preferred over one with additional lower-priority victims).
//  3. Victim structural importance: element-by-element from most to least important,
//     lower workload rank (Pod < PodGroup < CompositePodGroup) and smaller group size are
//     preferred, reflecting [compareVictimStructuralImportance].
//
// This function assumes the victim instances are subsets of the ones generated by [defaultPreemptionManager.GenerateVictims]
// in reversed order (as returned by [PodGroupPreemptionState.SurvivingVictimsOnNode]): PDB-violating victims ordered
// descending by [MoreImportantVictim], followed by non-violating victims ordered descending by [MoreImportantVictim].
// Elements must implement [Victim] (as produced by [defaultPreemptionManager.GenerateVictims]); passing a non-[Victim]
// implementation panics when priority and structural importance comparisons are reached.
func (m *defaultPreemptionManager) CompareVictimSets(_ context.Context, set1, set2 []fwk.PreemptionVictim) int {
	if len(set1) == 0 || len(set2) == 0 {
		return cmp.Compare(len(set1), len(set2))
	}

	// TODO(#142718): NumPDBViolations() is computed statically across all potential victims
	// in the domain, which is exact for DisruptionsAllowed == 0 but can miscount when
	// DisruptionsAllowed > 0 and earlier victims sharing the same PDB were not condemned.
	// Track DisruptionsAllowed dynamically in PodGroupPreemptionState.
	pdb1, split1 := countPDBViolations(set1)
	pdb2, split2 := countPDBViolations(set2)
	if c := cmp.Compare(pdb1, pdb2); c != 0 {
		return c
	}

	it1, it2 := newVictimIterator(set1, split1), newVictimIterator(set2, split2)
	for it1.peek() != nil && it2.peek() != nil {
		p1, p2 := it1.peek().Priority(), it2.peek().Priority()
		if c := cmp.Compare(p1, p2); c != 0 {
			return c
		}
		// Aggregate all victims in this priority band across both runs so a single multi-pod group
		// and multiple smaller victims at the same priority are compared by total evicted pods.
		var prioPods1, prioPods2 int
		for it1.peek() != nil && it1.peek().Priority() == p1 {
			prioPods1 += len(it1.next().Pods())
		}
		for it2.peek() != nil && it2.peek().Priority() == p2 {
			prioPods2 += len(it2.next().Pods())
		}
		if c := cmp.Compare(prioPods1, prioPods2); c != 0 {
			return c
		}
	}
	// All shared priority bands matched in priority and pod count; any remaining victims
	// mean that set evicts extra lower-priority pods.
	if it1.peek() != nil {
		return 1
	}
	if it2.peek() != nil {
		return -1
	}

	// Total pod counts in every priority band are equal. Break ties by structural importance
	// (Pod < PodGroup < CompositePodGroup, then smaller group size) from highest to lowest importance.
	it1, it2 = newVictimIterator(set1, split1), newVictimIterator(set2, split2)
	for it1.peek() != nil && it2.peek() != nil {
		vi1, vi2 := it1.next(), it2.next()
		if c := cmp.Compare(victimRank(vi1), victimRank(vi2)); c != 0 {
			return c
		}
		if c := cmp.Compare(len(vi1.Pods()), len(vi2.Pods())); c != 0 {
			return c
		}
	}

	return 0
}

// countPDBViolations sums PDB violations across the PDB-violating prefix of set
// and returns both the total violation count and the index where the non-violating suffix begins.
func countPDBViolations(set []fwk.PreemptionVictim) (total, split int) {
	for split < len(set) && set[split].NumPDBViolations() > 0 {
		total += set[split].NumPDBViolations()
		split++
	}
	return total, split
}

// victimIterator yields victims from a node's surviving victim slice in descending
// [MoreImportantVictim] order in O(N) time and O(1) space by merging its two sorted runs
// (the PDB-violating prefix and the non-violating suffix) on the fly.
type victimIterator struct {
	violating    []fwk.PreemptionVictim
	nonViolating []fwk.PreemptionVictim
	curr         Victim
}

func newVictimIterator(set []fwk.PreemptionVictim, split int) victimIterator {
	it := victimIterator{
		violating:    set[:split],
		nonViolating: set[split:],
	}
	it.advance()
	return it
}

func (it *victimIterator) peek() Victim {
	return it.curr
}

func (it *victimIterator) next() Victim {
	v := it.curr
	it.advance()
	return v
}

func (it *victimIterator) advance() {
	violating, nonViolating := headVictim(it.violating), headVictim(it.nonViolating)
	// Yield the higher-importance head first; when both victims tie, prefer violating to preserve original ordering.
	switch {
	case violating == nil && nonViolating == nil:
		it.curr = nil
	case nonViolating == nil || (violating != nil && !MoreImportantVictim(nonViolating, violating)):
		it.curr = violating
		it.violating = it.violating[1:]
	default:
		it.curr = nonViolating
		it.nonViolating = it.nonViolating[1:]
	}
}

func headVictim(s []fwk.PreemptionVictim) Victim {
	if len(s) == 0 {
		return nil
	}
	return s[0].(Victim)
}

