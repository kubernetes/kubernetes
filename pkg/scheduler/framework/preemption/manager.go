type defaultPreemptionManager struct {
	snapshot  fwk.SharedLister
	executor  fwk.PreemptionExecutor
	pdbLister policylisters.PodDisruptionBudgetLister
}

var _ fwk.PreemptionManager = &defaultPreemptionManager{}
var _ fwk.ReprieveFilter = &defaultPreemptionManager{}

// NewPreemptionManager creates a PreemptionManager using the provided handle
// and features for victim discovery and actuation.
func NewPreemptionManager(fh fwk.Handle, fts feature.Features) fwk.PreemptionManager {
	return &defaultPreemptionManager{
		snapshot:  fh.SnapshotSharedLister(),
		executor:  NewExecutor(fh, fts),
		pdbLister: fh.SharedInformerFactory().Policy().V1().PodDisruptionBudgets().Lister(),
	}
}

// GenerateVictims creates victims with grouping determined by the hierarchy's DisruptionPolicy and ordering determined by Priority and PDB violations.
func (m *defaultPreemptionManager) GenerateVictims(ctx context.Context, pgInfo fwk.PodGroupInfo) ([]fwk.PreemptionVictim, *fwk.Status) {
	logger := klog.FromContext(ctx)

	if getPreemptionPolicy(pgInfo) == v1.PreemptNever {
		msg := "not eligible due to preemptionPolicy=Never."
		logger.V(5).Info("Preemptor is not eligible for preemption", "preemptor", klog.KObj(pgInfo), "type", pgInfo.GetType(), "reason", msg)
		return nil, fwk.NewStatus(fwk.Unschedulable, msg)
	}

	victims, err := getWorkloadPreemptionVictims(logger, m.snapshot)
	if err != nil {
		return nil, fwk.AsStatus(fmt.Errorf("failed to get victims: %w", err))
	}

	pdbs, err := getPodDisruptionBudgets(m.pdbLister)
	if err != nil {
		return nil, fwk.AsStatus(fmt.Errorf("failed to get pod disruption budgets: %w", err))
	}

	return prepareDomainVictims(victims, pgInfo.GetPriority(), pdbs), nil
}

// CompareVictimSets compares the preemption cost of two victim sets by applying the following criteria in order:
//  1. PDB violations: the set whose eviction causes fewer PDB violations is preferred.
//  2. Priority bands (descending): at the highest priority level where the sets differ,
//     a lower priority or fewer evicted pods at that priority is preferred (a set with
//     no remaining victims is preferred over one with additional lower-priority victims).
//  3. Victim structural importance: element-by-element from most to least important,
//     lower workload rank (Pod < PodGroup < CompositePodGroup) and smaller group size are
//     preferred, reflecting [compareVictimStructuralImportance].
//
// This function assumes the victims of each set are subsets of the ones generated by
// [defaultPreemptionManager.GenerateVictims], ordered from most to least important
// (as returned by [PodGroupPreemptionState.SurvivingVictimsOnNode]).
// Elements must implement [Victim] (as produced by [defaultPreemptionManager.GenerateVictims]); passing a non-[Victim]
// implementation panics when priority and structural importance comparisons are reached.
func (m *defaultPreemptionManager) CompareVictimSets(_ context.Context, set1, set2 fwk.PreemptionVictimSet) int {
	victims1, victims2 := set1.Victims(), set2.Victims()
	if len(victims1) == 0 || len(victims2) == 0 {
		return cmp.Compare(len(victims1), len(victims2))
	}

	if c := cmp.Compare(set1.NumPDBViolations(), set2.NumPDBViolations()); c != 0 {
		return c
	}

	// Each iteration compares the highest remaining priority band of both sets.
	// next1 and next2 point at the first victim of the next band in each set.
	next1, next2 := 0, 0
	for next1 < len(victims1) && next2 < len(victims2) {
		p1, p2 := victims1[next1].(Victim).Priority(), victims2[next2].(Victim).Priority()
		if c := cmp.Compare(p1, p2); c != 0 {
			return c
		}
		// Aggregate all victims in this priority band so a single multi-pod group
		// and multiple smaller victims at the same priority are compared by total evicted pods.
		var prioPods1, prioPods2 int
		for ; next1 < len(victims1) && victims1[next1].(Victim).Priority() == p1; next1++ {
			prioPods1 += len(victims1[next1].Pods())
		}
		for ; next2 < len(victims2) && victims2[next2].(Victim).Priority() == p2; next2++ {
			prioPods2 += len(victims2[next2].Pods())
		}
		if c := cmp.Compare(prioPods1, prioPods2); c != 0 {
			return c
		}
	}
	// All shared priority bands matched in priority and pod count; any remaining victims
	// mean that set evicts extra lower-priority pods.
	if next1 < len(victims1) {
		return 1
	}
	if next2 < len(victims2) {
		return -1
	}

	// Total pod counts in every priority band are equal. Break ties by structural importance
	// (Pod < PodGroup < CompositePodGroup, then smaller group size) from highest to lowest importance.
	for i := range min(len(victims1), len(victims2)) {
		vi1, vi2 := victims1[i].(Victim), victims2[i].(Victim)
		if c := cmp.Compare(victimRank(vi1), victimRank(vi2)); c != 0 {
			return c
		}
		if c := cmp.Compare(len(vi1.Pods()), len(vi2.Pods())); c != 0 {
			return c
		}
	}

	return 0
}

func (m *defaultPreemptionManager) Executor() fwk.PreemptionExecutor {
	return m.executor
}

func (m *defaultPreemptionManager) NewReprieveFilter(_ context.Context, _ []fwk.PreemptionVictim) fwk.ReprieveFilter {
	return m
}

func (m *defaultPreemptionManager) ShouldAttemptReprieval(_ context.Context, _ fwk.PreemptionVictim) (bool, error) {
	return true, nil
}

func (m *defaultPreemptionManager) OnVictimReprieved(_ context.Context, _ fwk.PreemptionVictim) error {
	return nil
}

func getPreemptionPolicy(pgInfo fwk.PodGroupInfo) v1.PreemptionPolicy {
	if policy := pgInfo.GetPreemptionPolicy(); policy != "" {
		return policy
	}
	for _, pod := range pgInfo.GetAllUnscheduledPods() {
		if p := pod.Spec.PreemptionPolicy; p != nil && *p == v1.PreemptNever {
			return *p
		}
	}
	return v1.PreemptLowerPriority
}

type victimWithPDBViolations struct {
	Victim
	numPDBViolations int
	// pdbsPerPod stores matching PDBs for each pod in Victim.Pods() that is protected by at least one PDB (ignoring already disrupted pods).
	pdbsPerPod [][]*policy.PodDisruptionBudget
}

var _ fwk.PreemptionVictim = &victimWithPDBViolations{}

func (v *victimWithPDBViolations) NumPDBViolations() int {
	return v.numPDBViolations
}

// prepareDomainVictims filters domain victims that are eligible for preemption by preemptorPriority, computes their PDB
// violations using the provided pdbs, and returns them in two partitions: the non-violating victims first, followed by
// the violating victims, each partition sorted from the least to the most important victim. This way, the backward
// reprieve pass tries to reprieve the violating victims first, then the non-violating ones, each from the most to the
// least important.
func prepareDomainVictims(victims []Victim, preemptorPriority int32, pdbs []*policy.PodDisruptionBudget) []fwk.PreemptionVictim {
	var potentialVictims []*victimWithPDBViolations
	pdbDisruptionsAllowed := make(map[*policy.PodDisruptionBudget]int32)
	for _, victim := range victims {
		if victim.Priority() < preemptorPriority {
			vw := &victimWithPDBViolations{
				Victim:     victim,
				pdbsPerPod: getPDBsPerPod(victim, pdbs),
			}
			initPDBDisruptionsAllowed(pdbDisruptionsAllowed, vw)
			potentialVictims = append(potentialVictims, vw)
		}
	}

	sort.Slice(potentialVictims, func(i, j int) bool {
		return MoreImportantVictim(potentialVictims[i], potentialVictims[j])
	})

	// PDB disruptions should be consumed from the least to the most important victim.
	// If evicting any pod of the victim violates a PDB, the whole victim is violating.
	var violatingVictims, nonViolatingVictims []fwk.PreemptionVictim
	for _, vw := range slices.Backward(potentialVictims) {
		vw.numPDBViolations = countVictimPDBViolations(vw, pdbDisruptionsAllowed)
		if vw.numPDBViolations > 0 {
			violatingVictims = append(violatingVictims, vw)
		} else {
			nonViolatingVictims = append(nonViolatingVictims, vw)
		}
	}
	return append(nonViolatingVictims, violatingVictims...)
}
