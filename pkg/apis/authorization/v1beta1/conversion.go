// Convert_authorization_SubjectAccessReviewStatus_To_v1beta1_SubjectAccessReviewStatus explicitly does not propagate the ConditionalDecision field to the v1beta1
// object; the conversion is thus lossy. However, this is ok, as {Local,Self,}SubjectAccessReview objects are never stored.
func Convert_authorization_SubjectAccessReviewStatus_To_v1beta1_SubjectAccessReviewStatus(in *authorization.SubjectAccessReviewStatus, out *authorizationv1beta1.SubjectAccessReviewStatus, s conversion.Scope) error {
	// First run the autogenerated code, then apply special patches afterwards (not the other way around)
	if err := autoConvert_authorization_SubjectAccessReviewStatus_To_v1beta1_SubjectAccessReviewStatus(in, out, s); err != nil {
		return err
	}

	// in.ConditionalDecision != nil implies that the response is conditional; this is not expressible in v1beta1, so fail closed. Avoid re-implementation by
	// decoding the v1 version of it into the authorizer.ConditionsAwareDecision type, which has the correct FailureDecision method.
	// Note that our validation already enforces that when ConditionalDecision is set, all other top-level status fields must be empty, so we can
	// safely set out.Allowed, out.Denied, out.EvaluationError, out.Reason
	if in.ConditionalDecision != nil {

		v1SARSpec := &authorizationv1.SubjectAccessReviewStatus{}
		// Manually validated that the conversion does not use conversion.Scope
		if err := authorizationv1internal.Convert_authorization_SubjectAccessReviewStatus_To_v1_SubjectAccessReviewStatus(in.DeepCopy(), v1SARSpec, nil); err != nil {
			return fmt.Errorf("unexpected, cannot convert authorization.SubjectAccessReviewStatus to v1.SubjectAccessReviewStatus: %w", err)
		}

		decodedDecision := apiserverauthorizationv1.DeserializeConditionsAwareDecision(*v1SARSpec.ConditionalDecision, func(err error) authorizer.ConditionsAwareDecision {
			return authorizer.ConditionsAwareDecisionDeny("failed closed", fmt.Errorf("couldn't deserialize decision: %w", err))
		})

		if err := decodedDecision.Error(); err != nil {
			out.EvaluationError = err.Error()
		}
		if reason := decodedDecision.Reason(); len(reason) != 0 {
			out.Reason = reason
		}
		out.Allowed = false

		switch decodedDecision.FailureDecision() {
		case authorizer.DecisionDeny:
			out.Denied = true
		case authorizer.DecisionNoOpinion:
			out.Denied = false
		default:
			out.Denied = true // default Deny on unrecognized modes
		}
	}

	return nil
}
